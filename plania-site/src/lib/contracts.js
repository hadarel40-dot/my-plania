export function getContract(key, tier) {
  const isTravel = key === 'travel';
  return {
    title: isTravel ? 'הסכם שירות: תכנון טיול' : 'הסכם שירות: פתרונות דיגיטליים לעסק',
    sections: isTravel ? travelSections(tier) : businessSections(),
  };
}

export function contractToText(contract) {
  return [
    contract.title,
    `גרסה ${CONTRACT_VERSION}`,
    ...contract.sections.map(
      (section, i) =>
        `${i + 1}. ${section.title}\n${section.items.map((item, j) => `${i + 1}.${j + 1} ${item}`).join('\n')}`
    ),
  ].join('\n\n');
}